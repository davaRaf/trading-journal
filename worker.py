# -*- coding: utf-8 -*-
"""
Робітник: телеграм-бот, щоденний зліпок журналу і перечитування Notion.

Навіщо окремо від сайту. Досі все жило в одному процесі з сайтом — на
безкоштовному хостингу інакше й не виходило. Але сайт хочеться колись
запустити у двох копіях (щоб оновлення не роняло журнал), а бота і фонові
справи — ні: два боти почнуть виривати одне в одного повідомлення Телеграма,
а зліпок робитиметься двічі на добу замість одного разу.

Тому копій сайту може бути скільки завгодно (їм ставимо RUN_BOT=0 і
RUN_JOBS=0), а робітник — рівно один.

Руки для перечитування Notion беремо з app.py: там уже написано, як класти
угоду, звідки брати налаштування і як дізнатись, що людина зараз переносить
журнал сама. Дублювати це тут не треба — імпорт app сервер не піднімає,
він стартує лише коли app.py запускають напряму.

Запуск:  python worker.py
"""
import threading

import config
import db


def main():
    db.init()

    # app імпортуємо заради його «рук» для notion_sync — сервер від цього
    # не піднімається (він за if __name__ == "__main__")
    import app
    import backup
    import notion_sync

    backup.start()
    notion_sync.start(add=app.add_trades, fill=app.blank_filler,
                      conf=app.notion_conf, save=app.notion_save,
                      shots=app.SHOTS, busy=app.import_busy)
    print("Робітник: зліпок журналу і Notion — працюють")

    if not config.BOT_TOKEN:
        # Без токена бота піднімати нічого, але й виходити не можна: хостинг
        # вважає процес, що завершився, впалим і перезапускає його по колу.
        print("BOT_TOKEN не заданий — бот не піднімається, фонові справи йдуть")
        threading.Event().wait()
        return

    import bot
    bot.main()


if __name__ == "__main__":
    main()
