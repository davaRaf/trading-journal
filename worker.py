# -*- coding: utf-8 -*-
"""
Робітник: телеграм-бот і щоденний зліпок журналу.

Навіщо окремо від сайту. Досі все жило в одному процесі з сайтом — на
безкоштовному хостингу інакше й не виходило. Але сайт хочеться колись
запустити у двох копіях (щоб оновлення не роняло журнал), а бота і зліпок
— ні: два боти почнуть виривати одне в одного повідомлення Телеграма,
а зліпок робитиметься двічі на добу замість одного разу.

Тому копій сайту може бути скільки завгодно (їм ставимо RUN_BOT=0 і
RUN_JOBS=0), а робітник — рівно один.

Запуск:  python worker.py
"""
import threading

import config
import db


def main():
    db.init()

    import backup

    backup.start()
    print("Робітник: зліпок журналу — працює")

    if not config.BOT_TOKEN:
        # Без токена бота піднімати нічого, але й виходити не можна: хостинг
        # вважає процес, що завершився, впалим і перезапускає його по колу.
        print("BOT_TOKEN не заданий — бот не піднімається, зліпок журналу йде")
        threading.Event().wait()
        return

    import bot
    bot.main()


if __name__ == "__main__":
    main()
