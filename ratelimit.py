"""
Скільки разів поспіль можна не вгадати пароль.

До цього /api/auth/login приймав спроби без ліку: скрипт міг перебирати
паролі до відомої пошти скільки завгодно швидко. Тут простий лічильник —
5 невдалих спроб за хвилину, далі відповідь «зачекай», аж поки найстаріша
з тих п'яти не випаде з хвилинного вікна.

Рахуємо по двох ключах одразу: за адресою гостя (один комп'ютер не може
довбати різні акаунти) і за самим логіном (розподілений перебір одного
акаунта з різних адрес теж упреться в межу).

Тримаємо в пам'яті процесу: сервер у нас один, а переживати перезапуск
такому лічильнику не треба — після перезапуску всім і так дається нові
п'ять спроб, і це не робить перебір реальним.

Самої хвилинної межі мало проти впертого перебору: п'ять спроб щохвилини
цілодобово — це понад сім тисяч паролів на добу, і словник коротких
паролів так перебирається. Тому поруч живе другий лічильник, з вікном на
годину, і за впертість пауза росте сходинками (STEPS). Ці сходинки
рахують тільки там, де вгадують секрет — вхід, код із листа, код із
застосунку; на звичайних запитах лишається сама хвилинна межа.
"""
import threading
import time

LIMIT = 5                 # невдалих спроб
WINDOW = 60               # за скільки секунд
MAX_KEYS = 5000           # більше в пам'яті не тримаємо

# Скільки невдач за годину — і на скільки після цього замикаємо. Пауза
# рахується від останньої спроби: не вгамувався — чекає спочатку.
# Сходинки підібрані так, щоб людина, яка справді забула пароль, їх не
# помітила (вона пробує три-чотири рази й іде за посиланням), а скрипт
# уперся після десятка.
STEPS = ((10, 5 * 60), (20, 30 * 60), (40, 2 * 3600))
LONG_WINDOW = 3600        # вікно довгого лічильника

_lock = threading.Lock()
_hits = {}                # ключ -> моменти невдалих спроб, за зростанням
_slow = {}                # те саме, але за годину — для сходинок


def _fresh(now, times):
    return [t for t in times if now - t < WINDOW]


def _sweep(now):
    """Прибрати ключі, у яких усі спроби вже застаріли."""
    for k in list(_hits):
        left = _fresh(now, _hits[k])
        if left:
            _hits[k] = left
        else:
            _hits.pop(k, None)


def check(keys, limit=LIMIT):
    """Скільки секунд чекати цьому гостю. 0 — можна пробувати.

    limit — своя межа для ключів, де 5 замало (питання до помічника)."""
    now = time.time()
    wait = 0
    with _lock:
        for k in keys:
            times = _fresh(now, _hits.get(k) or [])
            if times:
                _hits[k] = times
            else:
                _hits.pop(k, None)
            if len(times) >= limit:
                # чекаємо, поки найстаріша з останніх limit спроб випаде з вікна
                wait = max(wait, int(WINDOW - (now - times[-limit])) + 1)
    return wait


def miss(keys, limit=LIMIT):
    """Не вгадав пароль (або просто ще одна спроба, якщо рахуємо кожну)."""
    now = time.time()
    with _lock:
        if len(_hits) > MAX_KEYS:
            _sweep(now)
        for k in keys:
            times = _fresh(now, _hits.get(k) or [])
            times.append(now)
            _hits[k] = times[-limit:]


def forget(keys):
    """Зайшов — попередні промахи більше не рахуються."""
    with _lock:
        for k in keys:
            _hits.pop(k, None)


# ------------------------------------------------- сходинки за впертість ----

def _fresh_long(now, times):
    return [t for t in times if now - t < LONG_WINDOW]


def _sweep_long(now):
    for k in list(_slow):
        left = _fresh_long(now, _slow[k])
        if left:
            _slow[k] = left
        else:
            _slow.pop(k, None)


def fail(keys, limit=LIMIT):
    """Не вгадав секрет. Те саме, що miss, але ще й у годинний лічильник —
    звідси беруться сходинки. Кличемо тільки на входах, де щось угадують."""
    miss(keys, limit)
    now = time.time()
    with _lock:
        if len(_slow) > MAX_KEYS:
            _sweep_long(now)
        for k in keys:
            times = _fresh_long(now, _slow.get(k) or [])
            times.append(now)
            # довше за найсуворішу сходинку тримати нема сенсу
            _slow[k] = times[-STEPS[-1][0]:]


def locked(keys, limit=LIMIT):
    """Скільки секунд чекати цьому гостю: хвилинна межа плюс сходинки.

    0 — можна пробувати."""
    wait = check(keys, limit)
    now = time.time()
    with _lock:
        for k in keys:
            times = _fresh_long(now, _slow.get(k) or [])
            if not times:
                _slow.pop(k, None)
                continue
            _slow[k] = times
            for need, pause in STEPS:
                if len(times) >= need:
                    wait = max(wait, int(pause - (now - times[-1])) + 1)
    return max(wait, 0)


def fails(key):
    """Скільки невдач за цим ключем за останню годину. Потрібне тому, хто
    вирішує, чи вже час сказати людині, що її акаунт підбирають."""
    now = time.time()
    with _lock:
        times = _fresh_long(now, _slow.get(key) or [])
        if times:
            _slow[key] = times
        else:
            _slow.pop(key, None)
        return len(times)


def clear(keys):
    """Зайшов — забуваємо і хвилинні промахи, і годинні."""
    forget(keys)
    with _lock:
        for k in keys:
            _slow.pop(k, None)


# ---------------------------------------------- загальна межа на запити ----
#
# Все вище рахує невдачі на одному вході. Тут — інше: скільки взагалі
# запитів приймаємо з однієї адреси. Потрібне проти напливу, коли сайт
# просто засипають — байдуже чим, сторінкою чи картинкою: робітників у
# нас 64, і тисяча запитів на секунду з одного джерела займе всіх, поки
# люди стоятимуть у черзі.
#
# Межа щедра навмисно. Один захід на головну — це під сотню запитів
# поспіль: сторінка, стилі, три десятки скриптів, шрифти, картинки. Тому
# й межа не «скільки треба людині», а вшестеро більша: кілька вкладок,
# оновлення сторінки й порожній кеш мають уміщатись без пригод. Потік із
# одного джерела впирається в неї однаково — це десять запитів на секунду
# без упину, чого браузер не робить.
#
# Лічильник тут найпростіший, з вікном, що скидається: на напливі
# важливо не порахувати точно, а дешево відсікти. Списку моментів, як
# вище, ми собі дозволити не можемо — саме він і з'їв би пам'ять.

FLOOD_LIMIT = 600         # запитів з однієї адреси
FLOOD_WINDOW = 60         # за скільки секунд

_flood = {}               # адреса -> (скільки, коли почали рахувати)


def flood(key, limit=FLOOD_LIMIT, window=FLOOD_WINDOW):
    """Ще один запит із цієї адреси. Скільки секунд чекати; 0 — пропускаємо."""
    now = time.time()
    with _lock:
        if len(_flood) > MAX_KEYS:
            # Прибирати по одному тут дорого, а сам словник — не пам'ять
            # про людей, а лише лічильник хвилини. Тому на переповненні
            # чистимо все: у найгіршому разі напливу дадуть нове вікно.
            _flood.clear()
        n, started = _flood.get(key) or (0, now)
        if now - started >= window:
            n, started = 0, now
        n += 1
        _flood[key] = (n, started)
        if n > limit:
            return int(window - (now - started)) + 1
    return 0
